# String
flower = input("Masukkan nama bunga: ")
description = input("Deskripsikan bunga tersebut: ")

# Integer
petals = int(input("Masukkan jumlah kelopak bunga: "))

# Float
height = float(input("Masukkan tinggi bunga dalam cm: "))

# Boolean
fragrant = input("Apakah bunga memiliki aroma? (True/False): ")

print("FLOWER INFORMATION")
print("=====================")
print("Nama bunga      :", flower)
print("Deskripsi       :", description)
print("Jumlah kelopak  :", petals)
print("Tinggi bunga    :", height, "cm")
print("Memiliki aroma  :", fragrant)
