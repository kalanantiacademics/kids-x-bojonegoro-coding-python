print("Print menggunakan FOR:")
for i in range(5):
    print('Looping using FOR!')

print("Berhitung menggunakan FOR dengan range(10):")
for i in range(10):
    print('Berhitung ke-', i)

print("Berhitung menggunakan FOR dengan range(0, 11, 2):")
for i in range(0, 11, 2):
    print("Berhitung ke-", i)